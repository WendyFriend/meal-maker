export type CommonQuickAddCategoryId =
    'vegetables' | 'proteins' | 'grains' | 'nuts-seeds';

type CommonIngredient = IngredientInfo & {
    caloriesPer100g: number;
    proteinPer100g: number;
    carbohydratePer100g: number;
    fatPer100g: number;
};

function ingredient(
    name: string,
    fdcId: number,
    description: string,
    nutrition: Omit<CommonIngredient, 'name' | 'nutritionSource'>,
): CommonIngredient {
    return {
        name,
        nutritionSource: { fdcId, description },
        ...nutrition,
    };
}

